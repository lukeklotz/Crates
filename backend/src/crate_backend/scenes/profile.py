"""Count the release-group dump by scene, year, term and artist, and render
the counts as a Markdown report for tuning scenes.toml.

Plan: docs/superpowers/plans/2026-10-21-scene-catalog-expansion.md
"""

from collections import Counter, defaultdict
from dataclasses import dataclass, field
from typing import Any

from crate_backend.musicbrainz.extract import ALLOWED_SECONDARY_TYPES
from crate_backend.scenes.config import SceneConfig, SelectionSettings
from crate_backend.scenes.pool import PoolAlbum
from crate_backend.scenes.select import is_deep_cut

TOP_TERMS = 300
TOP_ARTISTS = 25
NO_YEAR = "no year"
# Batch sizes the plan budgets for, shown per scene against its pool.
BATCH_TARGETS = (25_000, 50_000)
_ARTIST_BUCKETS = ((1, 1, "1"), (2, 3, "2–3"), (4, 9, "4–9"), (10, 24, "10–24"), (25, None, "25+"))


def _decade(year: int | None) -> str:
    return NO_YEAR if year is None else f"{year // 10 * 10}s"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


@dataclass
class ProfileCounts:
    settings: SelectionSettings
    release_groups: int = 0
    album_primary: int = 0
    allowed_types: int = 0
    with_any_term: int = 0
    with_descriptive_term: int = 0
    no_year: int = 0
    in_scene: int = 0
    in_scene_in_catalog: int = 0
    catalog_in_pool: int = 0
    catalog_scene: Counter = field(default_factory=Counter)
    scene_studio: Counter = field(default_factory=Counter)
    scene_live: Counter = field(default_factory=Counter)
    scene_in_catalog: Counter = field(default_factory=Counter)
    scene_deep_cut: Counter = field(default_factory=Counter)
    scene_connectors: Counter = field(default_factory=Counter)
    scene_artists: defaultdict = field(default_factory=lambda: defaultdict(Counter))
    scene_terms: defaultdict = field(default_factory=lambda: defaultdict(Counter))
    decade_eligible: Counter = field(default_factory=Counter)
    decade_in_scene: Counter = field(default_factory=Counter)
    term_albums: Counter = field(default_factory=Counter)
    artist_albums: Counter = field(default_factory=Counter)

    def add_release_group(
        self, record: dict[str, Any], pool_album: PoolAlbum | None, in_catalog: bool
    ) -> None:
        """Count one dump record. `pool_album` is its to_pool_album result."""
        self.release_groups += 1
        if record.get("primary-type") != "Album":
            return
        self.album_primary += 1
        if not all(t in ALLOWED_SECONDARY_TYPES for t in record.get("secondary-types") or []):
            return
        self.allowed_types += 1
        if not (record.get("genres") or record.get("tags")):
            return
        self.with_any_term += 1
        if pool_album is None:
            return
        self.with_descriptive_term += 1
        self.catalog_in_pool += in_catalog
        self.term_albums.update(pool_album.terms.keys())
        self.decade_eligible[_decade(pool_album.year)] += 1
        if pool_album.year is None:
            self.no_year += 1
        match = pool_album.match
        if match is None:
            return
        scene = match.home
        self.in_scene += 1
        self.decade_in_scene[_decade(pool_album.year)] += 1
        artist = pool_album.artist_name or "(no artist)"
        self.artist_albums[artist] += 1
        self.scene_artists[scene][artist] += 1
        self.scene_terms[scene].update(match.matched_terms)
        (self.scene_live if pool_album.is_live else self.scene_studio)[scene] += 1
        self.scene_deep_cut[scene] += is_deep_cut(pool_album, self.settings)
        self.scene_connectors[scene] += bool(match.connects_to)
        if in_catalog:
            self.in_scene_in_catalog += 1
            self.scene_in_catalog[scene] += 1
            self.catalog_scene[scene] += 1


def _term_scenes(term: str, config: SceneConfig) -> str:
    scenes = [
        s.id
        for s in config.scenes
        if term in s.terms or term in s.broad_terms or term in s.requires_any
    ]
    label = ", ".join(scenes) if scenes else "unassigned"
    if term in config.deprioritized_terms:
        label += ", deprioritized"
    return label


def _years(years: tuple[int, int | None]) -> str:
    start, end = years
    return f"{start}–{end if end is not None else 'now'}"


def render_profile(
    counts: ProfileCounts, config: SceneConfig, *, snapshot: str, catalog_size: int
) -> str:
    total_share = sum(s.share for s in config.scenes)
    lines = [
        f"# Scene pool profile ({snapshot})",
        "",
        (
            "Generated by `crate_backend.scripts.profile_catalog_pool` from the MusicBrainz "
            "release-group dump and `catalog/scenes.toml`. Re-run with `--from-pool` after "
            "editing scenes.toml."
        ),
        "",
        "## Funnel",
        "",
        "| Step | Release groups |",
        "|---|---|",
        f"| All release groups | {counts.release_groups:,} |",
        f"| Primary type Album | {counts.album_primary:,} |",
        f"| Studio or Live only | {counts.allowed_types:,} |",
        f"| With any genre or tag | {counts.with_any_term:,} |",
        f"| With a positive descriptive term (the pool) | {counts.with_descriptive_term:,} |",
        f"| …of which no usable first-release year | {counts.no_year:,} |",
        f"| In a scene | {counts.in_scene:,} |",
        f"| In a scene and already in the catalog | {counts.in_scene_in_catalog:,} |",
        "",
        "## Scenes",
        "",
        (
            "Budget columns are this scene's share of a batch of that size; compare them with "
            "*Not in catalog* to see which scenes will run short."
        ),
        "",
        "| Scene | Tier | Years | Studio | Live | In catalog | Not in catalog | "
        + " | ".join(f"+{t // 1000}k budget" for t in BATCH_TARGETS)
        + " | Deep-cut candidates | Connector candidates | Artists | Top artists | Top terms |",
        "|---" * (14 + len(BATCH_TARGETS) - 2) + "|",
    ]
    for scene in config.scenes:
        sid = scene.id
        total = counts.scene_studio[sid] + counts.scene_live[sid]
        top_artists = ", ".join(
            f"{_cell(name)} ({n})" for name, n in counts.scene_artists[sid].most_common(5)
        )
        top_terms = ", ".join(f"{t} ({n})" for t, n in counts.scene_terms[sid].most_common(5))
        budgets = " | ".join(f"{round(t * scene.share / total_share):,}" for t in BATCH_TARGETS)
        lines.append(
            f"| {sid} | {scene.tier} | {_years(scene.years)} | {counts.scene_studio[sid]:,} | "
            f"{counts.scene_live[sid]:,} | {counts.scene_in_catalog[sid]:,} | "
            f"{total - counts.scene_in_catalog[sid]:,} | {budgets} | "
            f"{counts.scene_deep_cut[sid]:,} | "
            f"{counts.scene_connectors[sid]:,} | {len(counts.scene_artists[sid]):,} | "
            f"{top_artists} | {top_terms} |"
        )

    decades = sorted(k for k in counts.decade_eligible if k != NO_YEAR)
    if NO_YEAR in counts.decade_eligible:
        decades.append(NO_YEAR)
    lines += ["", "## Years", "", "| Decade | In the pool | In a scene |", "|---|---|---|"]
    for decade in decades:
        lines.append(
            f"| {decade} | {counts.decade_eligible[decade]:,} | {counts.decade_in_scene[decade]:,} |"
        )

    lines += [
        "",
        "## Terms",
        "",
        (
            f"The {TOP_TERMS} descriptive terms on the most pool albums. *unassigned* terms "
            "belong to no scene: add real spellings to a scene, or junk to nondescriptive_terms."
        ),
        "",
        "| Term | Albums | Scenes |",
        "|---|---|---|",
    ]
    for term, n in counts.term_albums.most_common(TOP_TERMS):
        lines.append(f"| {_cell(term)} | {n:,} | {_term_scenes(term, config)} |")

    per_artist = Counter()
    for n in counts.artist_albums.values():
        for low, high, label in _ARTIST_BUCKETS:
            if n >= low and (high is None or n <= high):
                per_artist[label] += 1
    lines += [
        "",
        "## Artists",
        "",
        "Albums per artist among in-scene albums (artist = the full credit as printed).",
        "",
        "| Albums per artist | Artists |",
        "|---|---|",
        *(f"| {label} | {per_artist[label]:,} |" for _, _, label in _ARTIST_BUCKETS),
        "",
        "| Artist | In-scene albums |",
        "|---|---|",
        *(
            f"| {_cell(name)} | {n:,} |"
            for name, n in counts.artist_albums.most_common(TOP_ARTISTS)
        ),
    ]

    in_scene = sum(counts.catalog_scene.values())
    lines += [
        "",
        "## Existing catalog",
        "",
        f"- Catalog albums: {catalog_size:,}",
        f"- In the pool: {counts.catalog_in_pool:,}",
        f"- In a scene: {in_scene:,}",
        f"- Not eligible under these rules (not in the pool): {catalog_size - counts.catalog_in_pool:,}",
        "",
        "| Scene | Catalog albums |",
        "|---|---|",
        *(f"| {s.id} | {counts.catalog_scene[s.id]:,} |" for s in config.scenes),
        "",
    ]
    return "\n".join(lines)
